type DeepString<T> = {
  [K in keyof T]: T[K] extends (...args: infer Args) => unknown
    ? (...args: Args) => string
    : T[K] extends object
    ? DeepString<T[K]>
    : string;
};

export type TranslationDictionary = DeepString<typeof translations.en>;
